export const PROMPT_IDS = PROMPT_DEFS.map((p) => p.id);
const DEFAULTS: Record<string, string> = Object.fromEntries(PROMPT_DEFS.map((p) => [p.id, p.text]));
export const defaultPrompt = (id: string): string => DEFAULTS[id] ?? "";

/** 사용자가 바꾼 프롬프트 (설정에서 받아 옴). 기본값과 같거나 없는 id 는 기본값 사용 */
let overrides: Record<string, string> = {};
export function setPromptOverrides(map: Record<string, string> | undefined) {
  overrides = map ?? {};
}
export const promptText = (id: string): string => (typeof overrides[id] === "string" ? overrides[id] : defaultPrompt(id));

/**
 * 프롬프트를 꺼내 ${이름} 을 값으로 바꾼다.
 * - 한 줄 전체가 ${이름} 이고 값이 비어 있으면 그 줄을 지운다 (빈 섹션이 빈 줄로 남지 않게)
 * - 틀의 빈 줄이 셋 이상 이어지면 둘로 줄이고, 앞뒤 빈 줄은 없앤다 (끼워 넣는 값은 그대로)
 */
export function P(id: string, vars: Record<string, string | number | undefined | null | false> = {}): string {
  return fill(promptText(id), vars);
}
export function fill(text: string, vars: Record<string, string | number | undefined | null | false> = {}): string {
  const val = (k: string) => {
    const v = vars[k];
    return v === undefined || v === null || v === false ? "" : String(v);
  };
  const has = (k: string) => Object.prototype.hasOwnProperty.call(vars, k);
  // 빈 줄 정리는 틀(template)에만 — 끼워 넣는 값(봇 설정 글 등)의 줄바꿈은 건드리지 않는다
  const frame = text
    .split("\n")
    .filter((line) => {
      const m = /^\s*\$\{([\p{L}\p{N}_]+)\}\s*$/u.exec(line);
      return !(m && has(m[1]) && !val(m[1]).trim());
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/^\n+|\n+$/g, "");
  return frame.replace(/\$\{([\p{L}\p{N}_]+)\}/gu, (all, k: string) => (has(k) ? val(k) : all));
}

/** 문서 내보내기·가져오기용: 기본값과 다른 것만 */
export function changedPrompts(map: Record<string, string> | undefined): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(map ?? {})) if (k in DEFAULTS && typeof v === "string" && v !== DEFAULTS[k]) out[k] = v;
  return out;
}
